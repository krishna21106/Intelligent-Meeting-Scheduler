CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

INSERT INTO roles (name) VALUES ('ADMIN'), ('OPERATOR'), ('VIEWER');

CREATE TABLE device_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

INSERT INTO device_types (name)
SELECT DISTINCT device_type FROM devices;

ALTER TABLE users
    ADD CONSTRAINT fk_users_role FOREIGN KEY (role_name) REFERENCES roles(name);

ALTER TABLE devices
    ADD CONSTRAINT fk_devices_type FOREIGN KEY (device_type) REFERENCES device_types(name);
