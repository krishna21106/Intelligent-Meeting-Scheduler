-- CNIP Network Manager - Schema Definition

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL,
    role_name VARCHAR(50) NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE devices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    ip_address VARCHAR(45) NOT NULL UNIQUE,
    device_type VARCHAR(50) NOT NULL,
    vendor VARCHAR(100) NOT NULL,
    model VARCHAR(100) NOT NULL,
    site VARCHAR(100) NOT NULL,
    location VARCHAR(150),
    status VARCHAR(50) NOT NULL DEFAULT 'UP',
    snmp_version VARCHAR(20) DEFAULT 'v2c',
    snmp_community VARCHAR(100) DEFAULT 'public',
    snmp_port INT DEFAULT 161,
    tags VARCHAR(255),
    last_seen TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_devices_ip ON devices(ip_address);
CREATE INDEX idx_devices_status ON devices(status);
CREATE INDEX idx_devices_site ON devices(site);

CREATE TABLE interfaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    mac_address VARCHAR(50),
    ip_address VARCHAR(45),
    status VARCHAR(20) NOT NULL DEFAULT 'UP',
    speed_bps BIGINT DEFAULT 1000000000,
    in_octets BIGINT DEFAULT 0,
    out_octets BIGINT DEFAULT 0,
    in_errors BIGINT DEFAULT 0,
    out_errors BIGINT DEFAULT 0,
    last_updated TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_interfaces_device FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE
);

CREATE INDEX idx_interfaces_device ON interfaces(device_id);

CREATE TABLE metrics (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    cpu_usage DOUBLE PRECISION NOT NULL,
    memory_usage DOUBLE PRECISION NOT NULL,
    latency_ms DOUBLE PRECISION NOT NULL,
    packet_loss_pct DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    bytes_in_per_sec BIGINT NOT NULL DEFAULT 0,
    bytes_out_per_sec BIGINT NOT NULL DEFAULT 0,
    uptime_seconds BIGINT NOT NULL DEFAULT 0,
    recorded_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_metrics_device FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE
);

CREATE INDEX idx_metrics_device_time ON metrics(device_id, recorded_at);
CREATE INDEX idx_metrics_recorded_at ON metrics(recorded_at);

CREATE TABLE alert_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    metric_type VARCHAR(50) NOT NULL,
    operator VARCHAR(20) NOT NULL,
    threshold_value DOUBLE PRECISION NOT NULL,
    duration_seconds INT DEFAULT 60,
    severity VARCHAR(20) NOT NULL,
    enabled BOOLEAN DEFAULT TRUE NOT NULL
);

CREATE TABLE alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    rule_id BIGINT,
    severity VARCHAR(20) NOT NULL,
    title VARCHAR(200) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    triggered_at TIMESTAMP NOT NULL,
    acknowledged_at TIMESTAMP,
    resolved_at TIMESTAMP,
    acknowledged_by VARCHAR(100),
    CONSTRAINT fk_alerts_device FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE,
    CONSTRAINT fk_alerts_rule FOREIGN KEY (rule_id) REFERENCES alert_rules(id) ON DELETE SET NULL
);

CREATE INDEX idx_alerts_status ON alerts(status);
CREATE INDEX idx_alerts_device ON alerts(device_id);
CREATE INDEX idx_alerts_triggered_at ON alerts(triggered_at);

CREATE TABLE config_backups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id BIGINT NOT NULL,
    version INT NOT NULL,
    backup_type VARCHAR(50) NOT NULL DEFAULT 'RUNNING',
    configuration TEXT NOT NULL,
    checksum VARCHAR(64) NOT NULL,
    backed_up_at TIMESTAMP NOT NULL,
    backed_up_by VARCHAR(100) NOT NULL,
    CONSTRAINT fk_config_device FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE CASCADE
);

CREATE INDEX idx_config_device ON config_backups(device_id);

CREATE TABLE vlans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vlan_id INT NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    subnet VARCHAR(50) NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE ip_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address VARCHAR(45) NOT NULL UNIQUE,
    subnet VARCHAR(50) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    device_id BIGINT,
    vlan_id BIGINT,
    dns_name VARCHAR(150),
    CONSTRAINT fk_ip_device FOREIGN KEY (device_id) REFERENCES devices(id) ON DELETE SET NULL,
    CONSTRAINT fk_ip_vlan FOREIGN KEY (vlan_id) REFERENCES vlans(id) ON DELETE SET NULL
);

CREATE INDEX idx_ip_status ON ip_addresses(status);

CREATE TABLE topology_links (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_device_id BIGINT NOT NULL,
    target_device_id BIGINT NOT NULL,
    source_interface VARCHAR(100) NOT NULL,
    target_interface VARCHAR(100) NOT NULL,
    link_status VARCHAR(20) NOT NULL DEFAULT 'UP',
    bandwidth_utilization_pct DOUBLE PRECISION DEFAULT 0.0,
    capacity_mbps BIGINT DEFAULT 10000,
    CONSTRAINT fk_link_source FOREIGN KEY (source_device_id) REFERENCES devices(id) ON DELETE CASCADE,
    CONSTRAINT fk_link_target FOREIGN KEY (target_device_id) REFERENCES devices(id) ON DELETE CASCADE
);

CREATE TABLE audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(100) NOT NULL,
    entity_id VARCHAR(100),
    details VARCHAR(2000),
    client_ip VARCHAR(50),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_audit_created_at ON audit_logs(created_at);

CREATE TABLE notification_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_enabled BOOLEAN DEFAULT FALSE NOT NULL,
    recipient_emails VARCHAR(500),
    webhook_enabled BOOLEAN DEFAULT FALSE NOT NULL,
    webhook_url VARCHAR(500),
    min_severity VARCHAR(20) DEFAULT 'WARNING' NOT NULL,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

